const DICTS = { pl, en };
let lang = config.lang;

/** For tests: switch the language at runtime. */
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'pl';
}

export function getLang() {
  return lang;
}

/**
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function t(key, vars = {}) {
  const s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Apply an English description plus a Polish localization to a builder (command or option). */
export function describe(builder, key) {
  const [enDesc, plDesc] = DESCRIPTIONS[key];
  return builder.setDescription(enDesc).setDescriptionLocalizations({ pl: plDesc });
}
